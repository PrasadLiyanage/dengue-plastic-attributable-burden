###############################################################################
# 01_first_stage_dlnm.R
#
# First-stage distributed lag non-linear models (DLNM)
#
# ---------------------------------------------------------------------------
# PURPOSE
# ---------------------------------------------------------------------------
#
# Fits district-specific distributed lag non-linear models using confidential
# surveillance data and exports the intermediate model objects required for
# the second-stage meta-analysis.
#
# ---------------------------------------------------------------------------
# IMPORTANT
# ---------------------------------------------------------------------------
#
# This script cannot be executed without access to the confidential
# surveillance dataset used in the study.
#
# The public GitHub repository therefore distributes only the exported
# intermediate model objects generated by this script.
#
###############################################################################

library(dplyr)
library(dlnm)
library(splines)
library(mvmeta)

##----------------------------------------------------------------------------
## Analysis parameters
##----------------------------------------------------------------------------

exposure_var <- "G1_Waste_BI"

lag_period <- c(0,12)

meta_lags <- c(0,2,4,8,10,12)

min_observations <- 10

##----------------------------------------------------------------------------
## Initialise storage
##----------------------------------------------------------------------------

districts <- data_quality_summary$District

coef_overall <-
  matrix(
    NA,
    nrow = length(districts),
    ncol = 3,
    dimnames = list(districts,
                    paste0("b",1:3))
  )

vcov_overall <-
  vector("list",length(districts))

results_by_lag <-
  setNames(
    lapply(meta_lags,function(x) list()),
    paste0("lag",meta_lags)
  )

##----------------------------------------------------------------------------
## First-stage district models
##----------------------------------------------------------------------------

message("Running district-level DLNMs...")

for(i in seq_along(districts)){
  
  district_data <-
    
    final_analysis_data |>
    
    filter(
      District == districts[i]
    ) |>
    
    filter(
      !is.na(.data[[exposure_var]])
    )
  
  if(nrow(district_data) < min_observations)
    next
  
  district_ecdf <-
    ecdf(
      district_data[[exposure_var]]
    )
  
  district_data <-
    
    district_data |>
    
    mutate(
      ExposurePercentile =
        district_ecdf(
          .data[[exposure_var]]
        ) * 100
    )
  
  cb <-
    
    crossbasis(
      
      district_data$ExposurePercentile,
      
      lag = lag_period,
      
      argvar = list(
        fun = "ns",
        knots = c(25,75),
        Boundary.knots = c(0,100)
      ),
      
      arglag = list(
        fun = "ns",
        knots = 4
      )
    )
  
  model <-
    
    glm(
      
      Cases ~ cb +
        ns(time,df=3),
      
      family = quasipoisson(),
      
      data = district_data
    )
  
  cumulative_effect <-
    
    crossreduce(
      cb,
      model,
      type = "overall",
      cen = 0
    )
  
  coef_overall[i,] <-
    coef(cumulative_effect)
  
  vcov_overall[[i]] <-
    vcov(cumulative_effect)
  
  for(L in meta_lags){
    
    lag_effect <-
      
      crossreduce(
        cb,
        model,
        type = "lag",
        value = L,
        cen = 0
      )
    
    results_by_lag[[paste0("lag",L)]][[districts[i]]] <-
      
      list(
        
        coef =
          coef(lag_effect),
        
        vcov =
          vcov(lag_effect)
        
      )
  }
  
}

##----------------------------------------------------------------------------
## Second-stage meta-analysis
##----------------------------------------------------------------------------

keep <- !is.na(coef_overall[,1])

meta_overall <-
  
  mvmeta(
    
    coef_overall[keep,] ~ 1,
    
    S = vcov_overall[keep],
    
    method = "reml"
    
  )

summary(meta_overall)

##----------------------------------------------------------------------------
## Export intermediate model objects
##----------------------------------------------------------------------------

dir.create(
  "data/intermediate",
  recursive = TRUE,
  showWarnings = FALSE
)

saveRDS(
  coef_overall,
  "data/intermediate/coef_overall.rds"
)

saveRDS(
  vcov_overall,
  "data/intermediate/vcov_overall.rds"
)

saveRDS(
  results_by_lag,
  "data/intermediate/results_by_lag.rds"
)

saveRDS(
  meta_overall,
  "data/intermediate/meta_overall.rds"
)

message("Intermediate DLNM objects exported.")

