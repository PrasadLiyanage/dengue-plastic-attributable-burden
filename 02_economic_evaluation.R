#===============================================================================
# STEP 2. DEMOGRAPHIC AND CLINICAL MODEL PARAMETERS
#===============================================================================
#
# This section specifies demographic and clinical assumptions used in the
# probabilistic economic evaluation.
#
# These parameters represent study-derived epidemiological inputs required
# for estimation of mortality, years of life lost (YLL), disability-adjusted
# life years (DALYs), and healthcare costs.
#
# Components
# ----------
#
# 1. Annual age-specific mortality distributions
#
#    Separate mortality profiles are defined for each study year (2024 and
#    2025). Each profile contains:
#
#      • age_group
#      • representative midpoint age
#      • observed dengue deaths within each age group
#
#    These distributions are used only to allocate the total number of
#    attributable deaths across age groups during the Monte Carlo simulation.
#    Individual-level mortality records are not included.
#
#
# 2. Annual observed deaths
#
#    The total number of laboratory-confirmed dengue deaths reported during
#    each study year is provided separately. During each simulation iteration,
#    observed deaths are sampled from a Poisson distribution and multiplied
#    by the attributable fraction estimated from the DLNM.
#
#
# 3. Hospitalization age distribution
#
#    Hospitalized attributable cases are divided into paediatric and adult
#    populations using study-specific proportions:
#
#      prop_paed
#      prop_adult
#
#
# 4. Clinical severity distributions
#
#    Within each age category, hospitalized cases are further partitioned into
#
#      • Dengue Fever (DF)
#      • Dengue Haemorrhagic Fever (DHF)
#      • Dengue Shock Syndrome (DSS)
#
#    These probabilities determine healthcare resource utilisation, treatment
#    costs, and disability estimates during the economic evaluation.
#
# Notes
# -----
#
# • These values are fixed model inputs and are not estimated by the DLNM.
#
# • The parameters can be replaced by alternative surveillance or published
#   estimates when applying the model in other settings.
#
# • No confidential patient-level information is contained in this section.
#===============================================================================

