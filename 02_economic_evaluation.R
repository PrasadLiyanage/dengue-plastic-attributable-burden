#===============================================================================
# STEP 3. ECONOMIC PARAMETERS AND MACROECONOMIC ADJUSTMENT
#===============================================================================
#
# This section defines the economic parameters used in the probabilistic
# cost-of-illness and societal burden estimation.
#
# The economic evaluation estimates costs attributable to the exposure-related
# dengue burden identified through the DLNM framework.
#
# All monetary parameters are standardized to 2024/2025 USD values using:
#
#   • historical exchange rates
#   • inflation adjustment factors
#   • annual GDP estimates
#
# No individual-level economic records are included.
#
#------------------------------------------------------------------------------
# Components
#------------------------------------------------------------------------------
#
# 1. Currency conversion and inflation adjustment
#
# Historical healthcare cost estimates are converted into current USD values.
#
# Inputs:
#
#   usd_rate
#       Annual LKR-to-USD conversion rate used for standardization.
#
#   ex_2012, ex_2018, ex_2024
#       Historical exchange rates used to convert previously published costs.
#
#   inf_12_24, inf_18_24
#       Inflation multipliers used to adjust costs from previous price years
#       to the current analysis period.
#
#
#------------------------------------------------------------------------------
# 2. Healthcare provider costs
#------------------------------------------------------------------------------
#
# Healthcare costs include:
#
#   • ambulatory care
#   • inpatient ward care
#   • intensive care utilization
#
# Costs are stratified by:
#
#   • paediatric vs adult patients
#   • dengue fever (DF)
#   • dengue haemorrhagic fever (DHF)
#   • severe dengue requiring intensive care
#
# These costs contribute to the healthcare provider perspective.
#
# Uncertainty:
#
#   Provider costs are represented by gamma distributions.
#   A coefficient of variation (provider_cv) is used to introduce uncertainty
#   during Monte Carlo simulations.
#
#
#------------------------------------------------------------------------------
# 3. Household out-of-pocket expenditure
#------------------------------------------------------------------------------
#
# Household costs represent direct non-provider costs incurred by patients
# and families.
#
# The model assumes:
#
#   • log-normal uncertainty distribution
#   • mean and variance derived from previous dengue economic studies
#
# Parameters:
#
#   oop_mu
#       Mean parameter of the log-normal distribution.
#
#   oop_sigma
#       Standard deviation parameter of the log-normal distribution.
#
#
#------------------------------------------------------------------------------
# 4. Productivity losses and indirect costs
#------------------------------------------------------------------------------
#
# Indirect costs represent productivity losses associated with dengue illness.
#
# Components include:
#
#   • adult productivity losses
#   • caregiver/productivity losses associated with paediatric illness
#
# Adult indirect costs are represented using a log-normal distribution.
#
# Paediatric productivity losses are sampled from a uniform distribution
# between predefined lower and upper bounds.
#
#
#------------------------------------------------------------------------------
# 5. Disability weights and morbidity burden
#------------------------------------------------------------------------------
#
# Disability-adjusted life years (DALYs) are estimated from:
#
#   DALY = Years Lived with Disability (YLD)
#          +
#          Years of Life Lost (YLL)
#
# YLD calculations use disability weights for:
#
#   • ambulatory dengue illness
#   • hospitalized dengue illness
#
# Illness duration is expressed as years using the average dengue episode
# duration.
#
#
#------------------------------------------------------------------------------
# 6. Macroeconomic parameters
#------------------------------------------------------------------------------
#
# GDP per capita estimates are incorporated to estimate productivity losses
# associated with premature mortality.
#
# For each year:
#
#   • GDP uncertainty is represented using a gamma distribution.
#   • A coefficient of variation (gdp_cv) defines uncertainty.
#
# This allows mortality-related productivity losses to incorporate uncertainty
# in economic conditions.
#
#
#------------------------------------------------------------------------------
# 7. Vector control programme costs
#------------------------------------------------------------------------------
#
# Annual vector control expenditure is included to estimate the programme
# component of societal costs.
#
# Costs include:
#
#   • operational vector control expenditure
#   • personnel/labour expenditure
#
# These values are converted from LKR million to USD million.
#
#
#------------------------------------------------------------------------------
# 8. Monte Carlo cost sampling function
#------------------------------------------------------------------------------
#
# draw_gamma_cost()
#
# Generates uncertain cost estimates from gamma distributions.
#
# The gamma distribution is used because healthcare costs are:
#
#   • strictly positive
#   • right-skewed
#   • commonly represented by cost uncertainty models
#
# The function converts:
#
#   mean cost + coefficient of variation
#
# into gamma distribution parameters.
#
#
#------------------------------------------------------------------------------
# Summary
#------------------------------------------------------------------------------
#
# This section provides all economic assumptions required to reproduce the
# uncertainty-based cost, DALY, and societal burden estimation.
#
# These parameters are independent of confidential surveillance data and can be
# replaced with context-specific estimates for other countries or settings.
#
#===============================================================================


usd_rate <- 300.00
ex_2012  <- 131.0; ex_2018 <- 162.5; ex_2024 <- 300.9
inf_12_24 <- 2.67; inf_18_24 <- 2.10

c_ward_p_df_mean  <- (215 * ex_2012 * inf_12_24) / ex_2024
c_ward_p_dhf_mean <- (293 * ex_2012 * inf_12_24) / ex_2024
c_icu_p_dhf_mean  <- (609 * ex_2012 * inf_12_24) / ex_2024
c_ward_a_df_mean  <- (196 * ex_2012 * inf_12_24) / ex_2024
c_ward_a_dhf_mean <- (255 * ex_2012 * inf_12_24) / ex_2024
c_icu_a_dhf_mean  <- (866 * ex_2012 * inf_12_24) / ex_2024
c_ambulatory_mean <- (84  * ex_2012 * inf_12_24) / ex_2024
provider_cv        <- 0.20

oop_m <- (16.29 * ex_2018 * inf_18_24) / ex_2024
oop_mu <- log(oop_m) - 0.5 * log(1 + (14.02^2 / 16.29^2))
oop_sigma <- sqrt(log(1 + (14.02^2 / 16.29^2)))

ind_a <- (303.99 * ex_2018 * inf_18_24) / ex_2024
ind_adult_mu <- log(ind_a) - 0.5 * log(1 + (569.77^2 / 303.99^2))
ind_adult_sigma <- sqrt(log(1 + (569.77^2 / 303.99^2)))
ind_p_min <- 15.0; ind_p_max <- 33.0

daly_ambulatory_mean   <- 0.032; daly_ambulatory_sd   <- 0.006
daly_hospitalized_mean <- 0.036; daly_hospitalized_sd <- 0.007
dengue_duration_years  <- 14 / 365.25

# Dynamically mapped macro-economic horizons by year
gdp_lookup <- tibble(
  Year = c(2024, 2025),
  GDP_Capita_USD = c(4516.00, 4753.00) 
)
gdp_cv <- 0.10

labor_baseline_2024_lkr <- 21176298 + 91466737 + 286853355 
labor_baseline_2025_lkr <- 22290840 + 96280776 + 301950900

programme_lookup <- tibble(
  Year = c(2024, 2025),
  Operational_LKR_M = c(45.68 + 9.45 + (5.15 * 0.75), 67.01 + 18.90 + (1.22 * 0.75)),
  Labor_LKR_M       = c(labor_baseline_2024_lkr / 1e6, labor_baseline_2025_lkr / 1e6)
) %>%
  dplyr::mutate(Total_Vector_Control_USD_M = (Operational_LKR_M + Labor_LKR_M) / usd_rate)

draw_gamma_cost <- function(mean_value, cv) {
  shape <- 1 / (cv^2); scale <- mean_value / shape
  rgamma(1, shape = shape, scale = scale)
}

#------------------------------------------------------------------------------
# STEP 4: MONTE CARLO SIMULATION EXECUTION LOOP (NATIONAL STRATIFIED ENGINE)
#------------------------------------------------------------------------------

#===============================================================================
# STEP 4. MONTE CARLO SIMULATION AND ATTRIBUTABLE BURDEN ESTIMATION
#===============================================================================
#
# This section performs the probabilistic economic and epidemiological burden
# estimation using a Monte Carlo simulation framework.
#
# The simulation integrates:
#
#   1. DLNM-derived exposure-response uncertainty
#   2. Attributable fraction estimation
#   3. Age-stratified mortality estimation
#   4. Healthcare cost estimation
#   5. Productivity loss estimation
#   6. Disability-adjusted life year (DALY) estimation
#
# The model propagates uncertainty from the exposure-response relationship and
# economic parameters to generate uncertainty intervals for all outcomes.
#
#------------------------------------------------------------------------------
# 1. Propagation of DLNM uncertainty
#------------------------------------------------------------------------------
#
# The multivariate meta-analysis coefficients obtained from the first-stage DLNM
# are assumed to follow a multivariate normal distribution.
#
# For each Monte Carlo iteration:
#
#   • DLNM coefficients are sampled from:
#
#       beta ~ MVN(beta_hat, variance-covariance matrix)
#
#   • A corresponding exposure-response curve is reconstructed.
#
#   • Relative risks are estimated across the exposure percentile range.
#
# This approach incorporates uncertainty from the epidemiological model into
# attributable burden estimates.
#
#
#------------------------------------------------------------------------------
# 2. Exposure attribution framework
#------------------------------------------------------------------------------
#
# For each simulated exposure-response function:
#
#   Relative Risk (RR) is assigned to each district-year observation.
#
# The attributable fraction is calculated as:
#
#       AF = (RR - 1) / RR
#
# for RR > 1.
#
# Attributable cases are estimated as:
#
#       Attributable cases = AF × observed cases
#
# The resulting attributable cases represent the estimated dengue burden
# associated with the exposure under investigation.
#
#
#------------------------------------------------------------------------------
# 3. Policy scenario analysis
#------------------------------------------------------------------------------
#
# The model evaluates alternative assumptions regarding:
#
#   • retirement age:
#          60 years
#          65 years
#
#   • discount rates:
#          0%   (undiscounted)
#          3.5% (main analysis)
#          5%   (sensitivity analysis)
#
# These scenarios influence future productivity losses and mortality-related
# economic consequences.
#
#
#------------------------------------------------------------------------------
# 4. Healthcare cost simulation
#------------------------------------------------------------------------------
#
# Attributable cases are partitioned into:
#
#   • ambulatory cases
#   • hospitalized cases
#
# Hospitalized cases are further stratified by:
#
#   • paediatric/adult population
#   • dengue fever
#   • dengue haemorrhagic fever
#   • severe dengue requiring intensive care
#
# Healthcare costs are sampled probabilistically using gamma distributions
# defined by mean costs and coefficients of variation.
#
# Components include:
#
#   • healthcare provider costs
#   • vector control programme costs
#   • household out-of-pocket expenditure
#
#
#------------------------------------------------------------------------------
# 5. Productivity loss and mortality valuation
#------------------------------------------------------------------------------
#
# Mortality-related economic losses are estimated using a human capital
# approach.
#
# Attributable deaths are:
#
#   • sampled using observed annual mortality
#   • distributed across age groups according to mortality profiles
#   • valued using projected GDP per capita
#
# Future productivity losses are discounted according to the selected economic
# scenario.
#
#
#------------------------------------------------------------------------------
# 6. DALY estimation
#------------------------------------------------------------------------------
#
# Disability-adjusted life years are calculated as:
#
#       DALY = YLD + YLL
#
# where:
#
#   YLD:
#       Years lived with disability due to dengue illness.
#
#   YLL:
#       Years of life lost due to premature mortality.
#
# Disability weights and life expectancy assumptions are incorporated as
# probabilistic inputs.
#
#
#------------------------------------------------------------------------------
# 7. Simulation output generation
#------------------------------------------------------------------------------
#
# The simulation generates uncertainty distributions for:
#
# Epidemiological outcomes:
#
#   • attributable cases
#   • attributable fraction
#   • attributable deaths
#   • DALYs
#   • population-standardized rates
#
# Economic outcomes:
#
#   • healthcare provider costs
#   • programme costs
#   • household costs
#   • indirect costs
#   • mortality-related productivity losses
#   • total societal costs
#
# Results are summarized using:
#
#   • mean estimates
#   • 2.5th percentile
#   • 97.5th percentile
#
# representing the 95% uncertainty interval.
#
#
#------------------------------------------------------------------------------
# 8. Reproducibility
#------------------------------------------------------------------------------
#
# The random seed is fixed to ensure reproducibility.
#
# The simulation does not require access to individual-level records once the
# required DLNM model objects and aggregated intermediate inputs are available.
#
# This framework allows independent verification of the economic estimates while
# protecting confidential surveillance data.
#
#===============================================================================

set.seed(123)
n_sim <- 5000

national_population_denominator <- 21781800
coef_sim_matrix    <- MASS::mvrnorm(n_sim, coef(meta_overall), vcov(meta_overall))
vcov_zero_identity <- vcov(meta_overall) * 0

policy_scenarios <- expand.grid(
  Retirement = c(60, 65),
  Discount   = c("Main_3.5" = 0.035, "Undiscounted_0" = 0.000, "High_5.0" = 0.050),
  stringsAsFactors = FALSE
)

final_compiled_results <- list()

for (s in seq_len(nrow(policy_scenarios))) {
  retire_age <- policy_scenarios$Retirement[s]
  disc_rate  <- policy_scenarios$Discount[s]
  
  yearly_summary_accumulator <- list()
  
  for (yr in years) {
    data_year          <- ar_data %>% dplyr::filter(Year == yr)
    observed_deaths_yr <- observed_deaths_lookup %>% filter(Year == yr) %>% pull(Observed_Deaths)
    program_base_usd_m <- programme_lookup %>% filter(Year == yr) %>% pull(Total_Vector_Control_USD_M)
    
    # Stratify GDP distributions row-by-row inside the temporal engine loop
    target_gdp_base <- gdp_lookup %>% filter(Year == yr) %>% pull(GDP_Capita_USD)
    simulated_gdp_vector_stratified <- rgamma(n_sim, shape = 1/(gdp_cv^2), scale = target_gdp_base * (gdp_cv^2))
    
    active_demographics <- mortality_profiles_by_year[[as.character(yr)]]
    cohort_years_lost   <- pmax(retire_age - active_demographics$age_mid, 0)
    
    Provider_sim  <- numeric(n_sim); Program_sim   <- numeric(n_sim)
    Household_sim <- numeric(n_sim); Indirect_sim  <- numeric(n_sim); Mortality_sim <- numeric(n_sim)
    YLD_sim       <- numeric(n_sim); YLL_sim       <- numeric(n_sim)
    Cases_sim     <- numeric(n_sim); AF_sim        <- numeric(n_sim)
    Deaths_sim    <- numeric(n_sim); Societal_sim  <- numeric(n_sim) 
    
    for (i in seq_len(n_sim)) {
      
      pred_sim_loop <- crosspred(
        b_pred, coef = coef_sim_matrix[i, ], vcov = vcov_zero_identity, model.link = "log", cen = 0
      )
      rr_lookup_sim <- data.frame(Exp_Pct = round(pred_sim_loop$predvar), RR_sim = pred_sim_loop$allRRfit)
      
      loop_ar_data <- data_year %>%
        dplyr::select(-RR, -AF, -AN) %>%
        dplyr::left_join(rr_lookup_sim, by = c("Exp_Pct_round" = "Exp_Pct")) %>%
        dplyr::group_by(District) %>%
        dplyr::mutate(RR_sim = dplyr::if_else(is.na(RR_sim), 1, RR_sim),
                      AF_sim = dplyr::if_else(RR_sim > 1, (RR_sim - 1) / RR_sim, 0),
                      AN_sim = AF_sim * Cases) %>%
        dplyr::ungroup()
      
      an_cases  <- sum(loop_ar_data$AN_sim, na.rm = TRUE)
      mean_af   <- ifelse(sum(loop_ar_data$Cases) > 0, an_cases / sum(loop_ar_data$Cases), 0)
      
      hosp_cases <- an_cases * 0.25
      amb_cases  <- an_cases * 0.75
      
      Cases_sim[i] <- an_cases
      AF_sim[i]    <- mean_af * 100
      
      paed_cases <- hosp_cases * prop_paed; adult_cases <- hosp_cases * prop_adult
      p_df  <- paed_cases * sev_paed_df;  p_dhf  <- paed_cases * sev_paed_dhf;  p_dss  <- paed_cases * sev_paed_dss
      a_df  <- adult_cases * sev_adult_df; a_dhf  <- adult_cases * sev_adult_dhf; a_dss  <- adult_cases * sev_adult_dss
      
      c_w_p_df  <- draw_gamma_cost(c_ward_p_df_mean, provider_cv)
      c_w_p_dhf <- draw_gamma_cost(c_ward_p_dhf_mean, provider_cv)
      c_i_p_dss <- draw_gamma_cost(c_icu_p_dhf_mean, provider_cv)
      c_w_a_df  <- draw_gamma_cost(c_ward_a_df_mean, provider_cv)
      c_w_a_dhf <- draw_gamma_cost(c_ward_a_dhf_mean, provider_cv)
      c_i_a_dss <- draw_gamma_cost(c_icu_a_dhf_mean, provider_cv)
      c_amb     <- draw_gamma_cost(c_ambulatory_mean, provider_cv)
      
      Provider_sim[i] <- (
        (amb_cases * c_amb) +
          (p_df * c_w_p_df) +
          (p_dhf * c_w_p_dhf) +
          (p_dss * c_i_p_dss) +
          (a_df * c_w_a_df) +
          (a_dhf * c_w_a_dhf) +
          (a_dss * c_i_a_dss)
      ) / 1e6
      
      Program_sim[i]   <- program_base_usd_m * mean_af
      
      Household_sim[i] <- (an_cases * rlnorm(1, oop_mu, oop_sigma)) / 1e6
      Indirect_sim[i]  <- ((adult_cases * rlnorm(1, ind_adult_mu, ind_adult_sigma)) + (paed_cases * runif(1, ind_p_min, ind_p_max))) / 1e6
      
      observed_deaths_draw <- rpois(1, observed_deaths_yr)
      attributable_deaths_drawn <- mean_af * observed_deaths_draw
      Deaths_sim[i] <- attributable_deaths_drawn
      
      cohort_death_vector <- attributable_deaths_drawn * (active_demographics$observed_deaths / observed_deaths_yr)
      
      cohort_annuity_factors <- ifelse(disc_rate == 0 | cohort_years_lost <= 0,
                                       cohort_years_lost,
                                       (1 - (1 + disc_rate)^(-cohort_years_lost)) / disc_rate)
      
      # Dynamically bound to the year-specific macroeconomic simulation vector
      Mortality_sim[i] <- sum(cohort_death_vector * (simulated_gdp_vector_stratified[i] * cohort_annuity_factors)) / 1e6
      
      d_amb_weight  <- max(rnorm(1, daly_ambulatory_mean, daly_ambulatory_sd), 0)
      d_hosp_weight <- max(rnorm(1, daly_hospitalized_mean, daly_hospitalized_sd), 0)
      YLD_sim[i]    <- ((amb_cases * d_amb_weight) + (hosp_cases * d_hosp_weight)) * dengue_duration_years
      
      cohort_le_remaining    <- pmax(76.0 - active_demographics$age_mid, 0)
      cohort_yll_multipliers <- ifelse(disc_rate == 0,
                                       cohort_le_remaining,
                                       (1 - exp(-disc_rate * cohort_le_remaining)) / disc_rate)
      YLL_sim[i]             <- sum(cohort_death_vector * cohort_yll_multipliers)
      
      # Added missing iteration-level total cost compilation
      Societal_sim[i] <- Provider_sim[i] + Program_sim[i] + Household_sim[i] + Indirect_sim[i] + Mortality_sim[i]
    }
    
    total_daly_vector <- YLD_sim + YLL_sim
    
    yearly_summary_accumulator[[as.character(yr)]] <- tibble(
      Year = yr, Retirement_Age = retire_age, Discount_Rate = disc_rate,
      
      Cases_M   = round(mean(Cases_sim)), 
      Cases_L   = round(quantile(Cases_sim, 0.025)), 
      Cases_U   = round(quantile(Cases_sim, 0.975)),
      
      AF_M      = mean(AF_sim),   
